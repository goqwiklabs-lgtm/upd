def get_google_access_token(acc_row):
    """Refreshes and returns a valid Google OAuth access token."""
    try:
        data = urllib.parse.urlencode({
            'client_id': acc_row['client_id'],
            'client_secret': acc_row['client_secret'],
            'refresh_token': acc_row['refresh_token'],
            'grant_type': 'refresh_token'
        }).encode()
        req = urllib.request.Request('https://oauth2.googleapis.com/token', data=data)
        resp = urllib.request.urlopen(req, timeout=10)
        tok_data = json.loads(resp.read().decode())
        return tok_data.get('access_token')
    except Exception as e:
        print(f"[-] Token refresh error: {e}", file=sys.stderr)
        return None

def fetch_file_bytes(google_file_id, token, max_bytes=4194304):
    """Fetches up to max_bytes of a file directly from Google Drive."""
    try:
        url = f"https://www.googleapis.com/drive/v3/files/{google_file_id}?alt=media"
        req = urllib.request.Request(url)
        req.add_header('Authorization', f'Bearer {token}')
        req.add_header('Range', f'bytes=0-{max_bytes - 1}')
        resp = urllib.request.urlopen(req, timeout=15)
        return resp.read()
    except Exception as e:
        print(f"[-] Drive fetch error: {e}", file=sys.stderr)
        return b''

def compute_skin_percentage(pil_img):
    """
    Analyzes actual image pixels in RGB + YCbCr color spaces to detect skin-tone coverage.
    Returns skin pixel percentage (0.0 to 100.0).
    """
    try:
        img_rgb = pil_img.convert('RGB')
        thumb = img_rgb.resize((160, 160))
        # Use getdata or get_flattened_data
        try:
            pixels = list(thumb.getdata())
        except AttributeError:
            pixels = list(thumb.get_flattened_data())

        total = len(pixels)
        if total == 0:
            return 0.0

        skin_count = 0
        for r, g, b in pixels:
            # Kovac rule in RGB:
            if r > 95 and g > 40 and b > 20 and (max(r, g, b) - min(r, g, b) > 15) and abs(r - g) > 15 and r > g and r > b:
                # YCbCr verification:
                y = 0.299 * r + 0.587 * g + 0.114 * b
                cb = 128 - 0.168736 * r - 0.331264 * g + 0.5 * b
                cr = 128 + 0.5 * r - 0.418688 * g - 0.081312 * b
                if 80 <= y <= 255 and 85 <= cb <= 135 and 135 <= cr <= 180:
                    skin_count += 1

        return (skin_count / total) * 100.0
    except Exception as e:
        return 0.0

