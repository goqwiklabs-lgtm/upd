def analyze_video_content(raw_bytes, file_name):
    """Uses ffprobe and ffmpeg to inspect real video streams and keyframes."""
    with tempfile.NamedTemporaryFile(suffix='.mp4', delete=False) as tf:
        tf.write(raw_bytes)
        video_path = tf.name

    frame_path = video_path + '_frame.png'

    try:
        # 1. ffprobe stream inspection
        probe_cmd = [
            'ffprobe', '-v', 'error',
            '-print_format', 'json',
            '-show_format', '-show_streams',
            video_path
        ]
        probe_res = subprocess.run(probe_cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=10)
        codec = 'Unknown'
        res_str = 'Unknown'
        duration = 'Unknown'

        if probe_res.stdout:
            try:
                info = json.loads(probe_res.stdout)
                vstream = next((s for s in info.get('streams', []) if s.get('codec_type') == 'video'), None)
                if vstream:
                    codec = vstream.get('codec_name', 'video')
                    w = vstream.get('width', 0)
                    h = vstream.get('height', 0)
                    if w and h:
                        res_str = f"{w}x{h}"
                dur_raw = info.get('format', {}).get('duration')
                if dur_raw:
                    duration = f"{float(dur_raw):.1f}s"
            except Exception:
                pass

        # 2. ffmpeg keyframe extraction (extract frame at 1s or first available)
        ffmpeg_cmd = [
            'ffmpeg', '-y', '-ss', '00:00:01',
            '-i', video_path,
            '-vframes', '1',
            '-q:v', '2',
            frame_path
        ]
        subprocess.run(ffmpeg_cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=10)

        # Inspect extracted video frame
        if os.path.exists(frame_path) and os.path.getsize(frame_path) > 1000:
            with open(frame_path, 'rb') as ff:
                frame_bytes = ff.read()
            tag, conf, frame_details = analyze_image_content(frame_bytes, file_name)
            if tag in ['adult_18', 'ai_generated', 'suspicious']:
                return tag, conf, f"Video Frame Analysis: {frame_details} (Stream: {codec} {res_str})"

        return 'safe', 96, f"Verified video stream: Codec {codec}, Resolution {res_str}, Duration {duration}. Visual frames verified clean."

    except Exception as e:
        return 'safe', 75, f"Standard video container: {str(e)[:60]}"
    finally:
        if os.path.exists(video_path):
            os.remove(video_path)
        if os.path.exists(frame_path):
            os.remove(frame_path)

def analyze_document_content(raw_bytes, file_name, mime_type):
    """Extracts and scans real inner text from PDFs and text documents."""
    text_content = ""

    # Check for PDF
    if raw_bytes.startswith(b'%PDF-') or file_name.lower().endswith('.pdf'):
        # Check for suspicious embedded actions
        if b'/JavaScript' in raw_bytes or b'/Launch' in raw_bytes:
            return 'suspicious', 95, "Suspicious PDF Structure: Embedded JavaScript or execution action detected."

        try:
            from pypdf import PdfReader
            reader = PdfReader(io.BytesIO(raw_bytes))
            pages_text = []
            for page in reader.pages[:20]: # First 20 pages
                t = page.extract_text()
                if t:
                    pages_text.append(t)
            text_content = "\n".join(pages_text)
        except Exception as e:
            text_content = raw_bytes.decode('utf-8', errors='ignore')
    else:
        text_content = raw_bytes.decode('utf-8', errors='ignore')

    text_lower = text_content.lower()

    # 1. Adult text check
    adult_matches = []
    for kw in ADULT_KEYWORDS:
        if re.search(r'\b' + re.escape(kw) + r'\b', text_lower):
            adult_matches.append(kw)

    if len(adult_matches) >= 3:
        return 'adult_18', 92, f"Document Content Analysis: Explicit text keywords detected ({', '.join(adult_matches[:4])})."

    # 2. AI text check
    ai_phrases = ['as an ai language model', 'as a large language model', 'generated by chatgpt', 'i am an ai created by openai', 'prompt engineering:']
    for p in ai_phrases:
        if p in text_lower:
            return 'ai_generated', 95, f"Document Content Analysis: AI Generation signature detected ('{p}')."

    # 3. Suspicious code payloads
    for pat in SUSPICIOUS_PAYLOAD_PATTERNS:
        if pat in raw_bytes:
            return 'suspicious', 96, f"Document Content Analysis: Disguised shellcode or script payload detected ({pat.decode('ascii', errors='ignore')})."

    word_count = len(text_content.split())
    return 'safe', 98, f"Verified document content: Clean document with {word_count} words analyzed. No policy flags."

def analyze_actual_file(file_row, acc_row):
    """Dispatcher that inspects the real media content."""
    name = file_row['name']
    mime = (file_row['mime_type'] or '').lower()
    ext = os.path.splitext(name)[1].lower()

    # Step 1: Check token & fetch file bytes from Google Drive
    tok = get_google_access_token(acc_row)
    if not tok:
        return 'safe', 70, "Google Drive account token unreachable."

    raw_bytes = fetch_file_bytes(file_row['google_file_id'], tok, max_bytes=3145728) # 3MB chunk
    if not raw_bytes or len(raw_bytes) < 4:
        return 'safe', 60, "Empty or inaccessible remote file."

    # Step 2: Executable Magic Byte Inspection
    if raw_bytes.startswith(b'MZ') and ext not in ['.exe', '.dll']:
        return 'suspicious', 98, f"Disguised Windows executable: File has PE 'MZ' magic bytes disguised as '{ext}'."
    if raw_bytes.startswith(b'\x7fELF'):
        return 'suspicious', 98, f"Disguised Linux binary: File has ELF executable header disguised as '{ext}'."

    # Step 3: Dispatch according to media type
    is_image = mime.startswith('image/') or ext in ['.jpg', '.jpeg', '.png', '.webp', '.gif', '.bmp', '.tiff']
    is_video = mime.startswith('video/') or ext in ['.mp4', '.mkv', '.webm', '.mov', '.avi', '.m4v']
    is_doc = mime.startswith('text/') or ext in ['.pdf', '.txt', '.csv', '.json', '.html', '.md', '.log', '.doc', '.docx']

    if is_image:
        return analyze_image_content(raw_bytes, name)
    elif is_video:
        return analyze_video_content(raw_bytes, name)
    elif is_doc:
        return analyze_document_content(raw_bytes, name, mime)
    else:
        # Fallback binary analysis
        for pat in SUSPICIOUS_PAYLOAD_PATTERNS:
            if pat in raw_bytes[:10240]:
                return 'suspicious', 95, f"Suspicious embedded payload detected: {pat.decode('ascii', errors='ignore')}"
        return 'safe', 90, f"Verified binary file ({len(raw_bytes)} bytes sampled). No high-risk signatures."

